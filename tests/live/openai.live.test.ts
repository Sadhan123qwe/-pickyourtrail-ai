import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { TestClient } from "../support/client";
import { all } from "@/lib/db";
import { getAiConfig } from "@/lib/config";
import { runAiHealthCheck } from "@/lib/ai/health";
import * as login from "@/app/api/auth/login/route";
import * as chat from "@/app/api/ai/chat/route";
import * as start from "@/app/api/trips/preferences/route";
import * as generate from "@/app/api/itineraries/generate/route";
import * as voice from "@/app/api/ai/voice/session/route";
import * as command from "@/app/api/command/chat/route";

const live = getAiConfig().mode === "live";
const key = process.env.OPENAI_API_KEY ?? "";
// Capture everything the app logs so we can prove the key never appears in logs.
const logged: string[] = [];
const original = { log: console.log, warn: console.warn, error: console.error };
beforeAll(() => {
  for (const k of ["log", "warn", "error"] as const) console[k] = (...a: unknown[]) => (logged.push(a.map(String).join(" ")), original[k](...a));
});
afterAll(() => Object.assign(console, original));

if (!live) {
  describe("LIVE OpenAI integration", () => {
    it.skip(`BLOCKED — ${getAiConfig().reason} Add a new key to .env.local and run npm run test:live.`, () => {});
  });
} else {
  describe("LIVE OpenAI integration", () => {
    const noKey = (body: unknown) => expect(JSON.stringify(body)).not.toContain(key);

    it("health check: configuration, models, structured request and voice session all pass", async () => {
      const r = await runAiHealthCheck("test:live");
      for (const c of r.checks) console.log(`[live] ${c.status.toUpperCase()} ${c.name}: ${c.detail}`);
      expect(r.checks.filter((c) => c.status !== "passed")).toEqual([]);
      noKey(r);
    });

    it("plans a trip from natural language with a real model and persists it", async () => {
      const c = new TestClient();
      const tripId = (await c.call(start.POST, "POST", "/api/trips/preferences")).body.trip.id;
      const r = await c.call(chat.POST, "POST", "/api/ai/chat", {
        mode: "planner",
        tripId,
        message: "Plan a five-day family trip to Bali in December for two adults and two children aged six and nine. Our budget is 1.5 lakh rupees.",
      });
      expect(r.status).toBe(200);
      expect(r.body.ai.source).toBe("live");
      expect(r.body.profile).toMatchObject({ destinationId: "bali", durationDays: 5, adults: 2, children: 2, childrenAges: [6, 9], budgetAmount: 150000 });
      expect(["destination", "duration", "travellers", "childrenAges", "budget"]).not.toContain(r.body.turn.question?.key);
      noKey(r.body);
      const usage = all<{ provider: string; outcome: string; input_tokens: number; latency_ms: number }>("SELECT provider, outcome, input_tokens, latency_ms FROM usage_records WHERE category = 'planner' ORDER BY created_at DESC LIMIT 1")[0];
      expect(usage).toMatchObject({ provider: "openai", outcome: "ok" });
      expect(usage.input_tokens).toBeGreaterThan(0);
      console.log(`[live] planner turn: ${usage.input_tokens} input tokens, ${usage.latency_ms} ms`);

      // Answer the remaining essentials and generate an itinerary with the live model.
      await c.call(chat.POST, "POST", "/api/ai/chat", { mode: "planner", tripId, message: "Flexible within December, flying from Chennai, budget includes flights" });
      const g = await c.call(generate.POST, "POST", "/api/itineraries/generate", { tripId });
      expect([200, 201]).toContain(g.status);
      expect(g.body.itinerary.days).toHaveLength(5);
      expect(g.body.itinerary.budget.total).toBeGreaterThan(0); // computed in code from catalog prices
      console.log(`[live] itinerary generated by ${g.body.itinerary.generatedBy}`);
    });

    it("issues a real Realtime voice session only to the trip owner, without exposing the key", async () => {
      const c = new TestClient();
      const tripId = (await c.call(start.POST, "POST", "/api/trips/preferences")).body.trip.id;
      const r = await c.call(voice.POST, "POST", "/api/ai/voice/session", { tripId });
      expect(r.status).toBe(200);
      expect(typeof r.body.clientSecret).toBe("string");
      expect(r.body.clientSecret).not.toBe(key);
      noKey(r.body);
      const other = new TestClient();
      expect([403, 404]).toContain((await other.call(voice.POST, "POST", "/api/ai/voice/session", { tripId })).status);
    });

    it("employee copilot plans with the live model and only uses authorized tools", async () => {
      const sales = new TestClient();
      expect((await sales.call(login.POST, "POST", "/api/auth/login", { email: "sales@pyt-demo.test", password: "demo1234" })).status).toBe(200);
      const r = await sales.call(command.POST, "POST", "/api/command/chat", { message: "Give me a quick read on how our Bali pipeline looks and anything I should chase this week" });
      expect(r.status).toBe(200);
      expect(r.body.answer.length).toBeGreaterThan(20);
      for (const call of r.body.toolCalls) expect(["completed", "proposed", "failed"]).toContain(call.status);
      noKey(r.body);
      console.log(`[live] copilot planner=${r.body.ai.planner} composer=${r.body.ai.composer} tools=${r.body.toolCalls.map((t: { tool: string }) => t.tool).join(",")}`);
    });

    it("never writes the API key to logs", () => {
      expect(logged.join("\n")).not.toContain(key);
    });
  });
}
