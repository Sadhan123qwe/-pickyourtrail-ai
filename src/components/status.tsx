"use client";

import { Badge, StatusSteps } from "./ui";

/** Consistent status badges across customer and employee pages. */

const TRIP: Record<string, { label: string; tone: "neutral" | "blue" | "green" | "amber" | "red" | "violet" }> = {
  planning: { label: "Draft · planning", tone: "neutral" },
  itinerary_ready: { label: "Itinerary ready", tone: "blue" },
  saved: { label: "Saved", tone: "green" },
  handoff_requested: { label: "Booking requested", tone: "violet" },
  booked: { label: "Booked (provider confirmed)", tone: "green" },
  completed: { label: "Completed", tone: "neutral" },
  cancelled: { label: "Cancelled", tone: "red" },
};

export function TripStatusBadge({ status }: { status: string }) {
  const s = TRIP[status] ?? { label: status, tone: "neutral" as const };
  return <Badge tone={s.tone}>{s.label}</Badge>;
}

const LEAD: Record<string, "neutral" | "blue" | "green" | "amber" | "red" | "violet"> = {
  new: "blue",
  contacted: "violet",
  qualified: "amber",
  proposal_sent: "amber",
  won: "green",
  lost: "red",
};
export function LeadStageBadge({ stage }: { stage: string }) {
  return <Badge tone={LEAD[stage] ?? "neutral"}>{stage.replace(/_/g, " ").replace(/^\w/, (c) => c.toUpperCase())}</Badge>;
}

const TICKET: Record<string, "neutral" | "blue" | "green" | "amber" | "red" | "violet"> = {
  open: "blue",
  in_progress: "violet",
  pending_customer: "amber",
  escalated: "red",
  resolved: "green",
  closed: "neutral",
};
const TICKET_LABELS: Record<string, string> = {
  open: "Open",
  in_progress: "In progress",
  pending_customer: "Waiting on customer",
  escalated: "Escalated",
  resolved: "Resolved",
  closed: "Closed",
};
export function TicketStatusBadge({ status }: { status: string }) {
  return <Badge tone={TICKET[status] ?? "neutral"}>{TICKET_LABELS[status] ?? status}</Badge>;
}

const PRIORITY: Record<string, "neutral" | "blue" | "amber" | "red"> = { low: "neutral", normal: "blue", high: "amber", urgent: "red" };
export function PriorityBadge({ priority }: { priority: string }) {
  return (
    <Badge tone={PRIORITY[priority] ?? "neutral"}>
      {priority === "urgent" && <span aria-hidden>⚠</span>}
      {priority.charAt(0).toUpperCase() + priority.slice(1)}
    </Badge>
  );
}

const OPS: Record<string, { label: string; tone: "neutral" | "blue" | "green" | "amber" | "red" | "violet" }> = {
  pending: { label: "Pending review", tone: "amber" },
  in_review: { label: "In review", tone: "blue" },
  quote_sent: { label: "Quote sent", tone: "violet" },
  customer_accepted: { label: "Customer accepted", tone: "green" },
  failed: { label: "Failed", tone: "red" },
  cancelled: { label: "Cancelled", tone: "neutral" },
};
export function OpsStatusBadge({ status }: { status: string }) {
  const s = OPS[status] ?? { label: status, tone: "neutral" as const };
  return <Badge tone={s.tone}>{s.label}</Badge>;
}

export function ProviderStatusBadge({ status, reference }: { status: string; reference?: string | null }) {
  if (status === "provider_confirmed") return <Badge tone="green">Provider confirmed · {reference}</Badge>;
  if (status === "provider_failed") return <Badge tone="red">Provider failed</Badge>;
  if (status === "submitted") return <Badge tone="blue">Submitted to provider</Badge>;
  return (
    <Badge tone="neutral" title="No booking provider is connected in this demo">
      Not confirmed · no provider connected
    </Badge>
  );
}

export function AiSourceBadge({ source, model }: { source: string | null | undefined; model?: string | null }) {
  if (source === "live") return <Badge tone="green" title="Generated by the configured OpenAI model">Live AI{model ? ` · ${model}` : ""}</Badge>;
  if (source === "cache") return <Badge tone="blue" title="Reused a saved result; no new AI call">Reused result</Badge>;
  if (source === "fallback") return <Badge tone="amber" title="The AI call failed or was blocked, so the deterministic planner was used">Standard planner (AI fallback)</Badge>;
  return <Badge tone="neutral" title="Deterministic rules — no AI API call">Demo mode · rules-based</Badge>;
}

/**
 * One shared definition of the booking lifecycle, so every page distinguishes
 * an AI estimate from a request, a pending booking and a provider confirmation.
 */
export const LIFECYCLE_STEPS = [
  { key: "itinerary", label: "Itinerary & estimate", hint: "AI-generated, estimate only" },
  { key: "requested", label: "Quote requested", hint: "Handoff submitted to experts" },
  { key: "pending", label: "Booking pending", hint: "Expert checking suppliers" },
  { key: "confirmed", label: "Provider-confirmed", hint: "Needs supplier reference" },
];

export function lifecycleStage(input: { hasItinerary: boolean; opsStatus?: string | null; providerStatus?: string | null }): { key: string; failed: boolean; label: string } {
  if (input.providerStatus === "provider_confirmed") return { key: "confirmed", failed: false, label: "Booking confirmed by provider" };
  if (input.opsStatus && ["in_review", "quote_sent", "customer_accepted"].includes(input.opsStatus)) return { key: "pending", failed: false, label: "Booking pending — not confirmed" };
  if (input.opsStatus === "failed") return { key: "pending", failed: true, label: "Booking request failed" };
  if (input.opsStatus === "pending") return { key: "requested", failed: false, label: "Quote requested — not booked" };
  if (input.opsStatus === "cancelled") return { key: "itinerary", failed: true, label: "Request cancelled" };
  return { key: "itinerary", failed: false, label: input.hasItinerary ? "Itinerary estimate — nothing requested yet" : "Planning" };
}

export function BookingLifecycle({ hasItinerary, opsStatus, providerStatus }: { hasItinerary: boolean; opsStatus?: string | null; providerStatus?: string | null }) {
  const stage = lifecycleStage({ hasItinerary, opsStatus, providerStatus });
  return (
    <div className="space-y-2">
      <StatusSteps steps={LIFECYCLE_STEPS} current={stage.key} failed={stage.failed} />
      <p className="text-xs text-muted">{stage.label}. A trip is only booked when a supplier or booking provider returns a confirmation reference.</p>
    </div>
  );
}
